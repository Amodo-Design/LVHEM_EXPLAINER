#!/usr/bin/env python3
"""Create responsive WebP assets from the original photos (ImageMagick + cwebp)."""
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets' / 'web'
PHOTOS = {
    'compute': ('compute.jpg', (480, 960)),
    'recompute': ('recompute.jpeg', (320, 640)),
    'tap': ('TAP.jpg', (480, 960)),
}

for tool in ('magick', 'cwebp'):
    if not shutil.which(tool):
        raise SystemExit(f'{tool} is required (macOS: brew install imagemagick webp).')
OUT.mkdir(parents=True, exist_ok=True)
manifest = {}
with tempfile.TemporaryDirectory(prefix='lvhem-photos-') as temporary:
    for key, (filename, widths) in PHOTOS.items():
        source = ROOT / 'assets' / filename
        variants = []
        for width in widths:
            intermediate = Path(temporary) / f'{key}-{width}.png'
            output = OUT / f'{key}-{width}.webp'
            subprocess.run(['magick', str(source), '-auto-orient', '-colorspace', 'sRGB',
                            '-resize', f'{width}x>', '-strip', str(intermediate)], check=True)
            subprocess.run(['cwebp', '-quiet', '-q', '82', '-m', '6', '-metadata', 'none',
                            str(intermediate), '-o', str(output)], check=True)
            dimensions = subprocess.check_output(['magick', 'identify', '-format', '%w %h',
                                                  str(output)], text=True).split()
            variants.append({'src': output.relative_to(ROOT).as_posix(),
                             'width': int(dimensions[0]), 'height': int(dimensions[1]),
                             'bytes': output.stat().st_size})
        manifest[key] = {'source': f'assets/{filename}',
                         'sourceSHA256': hashlib.sha256(source.read_bytes()).hexdigest(),
                         'variants': variants}
        print(f'{key}: {source.stat().st_size:,} bytes → ' +
              ' / '.join(f'{v["width"]}px: {v["bytes"]:,} bytes' for v in variants))
(OUT / 'photos.js').write_text('// Generated by scripts/optimize-images.py; do not edit.\n'
                              + 'export default ' + json.dumps(manifest, indent=2) + ';\n')
