#!/usr/bin/env python3
"""Write ledger/exchanges.js: every recorded exchange the chat-and-ledger demo replays.

The source is the recorded zkml proofs of the LVHEM inference prototype, as
collected in that repository's zkml-demo/index.html (its `demo-data` block:
prompts, answer token ids with their text, and each proof's job record).

    python3 scripts/generate-ledger-exchanges.py /path/to/LVHEM_INFERENCE_ZKP_PROTOTYPE/zkml-demo/index.html

One exchange is not in that block and is written here by hand: the single
proof of 2026-10-14 ("What is the capital of France?").
"""

import json
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "ledger" / "exchanges.js"
EOS = {128009, 128001}

PARIS = {
    "id": "fow-01",
    "prompt": "What is the capital of France? Answer with one word.",
    "nPrompt": 47, "window": 256, "size": "3.39 GB",
    "tokens": [["Paris", 60704], ["", 128009]],
    "stages": [["Start-up and pre-check", 213], ["Commit", 54], ["Compute", 27], ["Prove", 775], ["Prover's own check", 129]],
}


def exchange(run: dict, prompts: dict) -> dict:
    rec = run["record"]
    b = rec["system_detail"]["buckets_s"]
    inner = b["commit"] + b["forward"] + b["prove"] + b["verify"]
    resp = run["response"]
    return {
        "id": run["prompt_id"],
        "prompt": prompts[run["prompt"]],
        "nPrompt": run["n_prompt"],
        "window": run["window"],
        "size": f"{rec['proof_size_bytes'] / 1e9:.2f} GB",
        # [text, id]; the end-of-answer token has no text.
        "tokens": [["" if i in EOS else piece, i] for piece, i in zip(resp["pieces"], resp["ids"])],
        "stages": [
            ["Start-up and pre-check", max(0, round(rec["job_wall_s"] - inner))],
            ["Commit", round(b["commit"])],
            ["Compute", round(b["forward"])],
            ["Prove", round(b["prove"])],
            ["Prover's own check", round(b["verify"])],
        ],
    }


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    page = Path(sys.argv[1]).read_text(encoding="utf-8")
    block = re.search(r'<script id="demo-data" type="application/json">(.*?)</script>', page, re.S)
    data = json.loads(block.group(1).replace("<\\/", "</"))
    runs = data["runs"]
    # The two answers that came from the serving model first, then the sweep in its own order.
    runs = [r for r in runs if r["answer_source"] == "vllm"] + [r for r in runs if r["answer_source"] != "vllm"]
    exchanges = [PARIS] + [exchange(r, data["prompts"]) for r in runs]
    lines = ",\n".join(" " + json.dumps(x, ensure_ascii=False, separators=(",", ":")) for x in exchanges)
    OUT.write_text(
        "// Generated by scripts/generate-ledger-exchanges.py from recorded zkml proofs. Do not edit by hand.\n"
        "// Each exchange: the prompt, its token count with the chat template, the proof's token window and\n"
        "// size, the answer as [text, token id] pairs, and the recorded seconds of each step of the proof job.\n"
        f"export const EXCHANGES = [\n{lines}\n];\n",
        encoding="utf-8",
    )
    tokens = sum(len(x["tokens"]) for x in exchanges)
    print(f"{len(exchanges)} exchanges, {tokens} answer tokens, {OUT.stat().st_size / 1024:.0f} KB -> {OUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
